#!/usr/bin/env node
/**
 * Genera el catálogo de filtros: qué existe en el repositorio y qué papel juega cada uno.
 *
 *   node scripts/catalog.mjs            escribe filters/catalog.json
 *   node scripts/catalog.mjs --check    sale 1 si el fichero no coincide con lo que se generaría
 *
 * POR QUÉ EXISTE. El registro del router cubre 31 de 48 filtros de recuperación y su regla
 * `registry_is_a_subset` mandaba «leer el índice del repositorio» antes de concluir que no hay filtro.
 * Ese índice no existía, y GitHub Pages no lista carpetas: desde una superficie conversacional, un
 * filtro no registrado era inencontrable (medido el 2026-10-16). Y aunque se encontrara, la carpeta no
 * dice cómo componerlo: `scope/` mezcla geografía, diseño, dominio, una lista de revistas y
 * exclusiones. Este catálogo da las dos cosas: qué hay, y su papel por defecto.
 *
 * QUÉ ES GENERADO Y QUÉ NO. Todo sale de los ficheros (cabecera `#`, bloque de metadatos, consulta) y
 * de `journal_filters_data.js`, salvo el papel, que no se puede deducir: lo declara el router en
 * `filter_catalog.role_of` y su significado en `composition.roles`. Un solo dueño por dato.
 *
 * QUÉ NO AFIRMA. `validation` resume lo que dice la cabecera (elaboración propia, adaptado de una
 * referencia, o referencia citada). Una referencia citada no prueba que el fichero sea la versión
 * validada: para eso hay que leer el filtro y su artículo.
 */

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseFilter, parseMetadata, isNegation, hasEmbeddedDateLimit } from './parse-filter.mjs';

const HERE = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const CATALOG_PATH = 'filters/catalog.json';
export const RETRIEVAL_DIRS = ['methodology', 'clinical', 'scope'];

const header = (text, key) => {
  const re = new RegExp(`^\\s*#\\s*${key}\\s*:\\s*(.*)$`, 'im');
  return (text.match(re)?.[1] ?? '').trim() || null;
};

const pairOf = (path, all) => {
  const m = path.match(/^(.*)_(sensible|especifico)\.txt$/);
  if (!m) return null;
  const other = `${m[1]}_${m[2] === 'sensible' ? 'especifico' : 'sensible'}.txt`;
  return all.includes(other) ? other : null;
};

export function buildCatalog(root = HERE) {
  const read = (p) => readFileSync(join(root, p), 'utf8');
  const router = JSON.parse(read('neurosymbolic_router.json'));
  const roleOf = router.filter_catalog?.role_of ?? {};
  const registryKey = {};
  for (const [cat, items] of Object.entries(router.filter_registry)) {
    for (const [k, p] of Object.entries(items)) registryKey[p] = `${cat}.${k}`;
  }

  const paths = RETRIEVAL_DIRS.flatMap((d) => readdirSync(join(root, 'filters', d))
    .filter((f) => f.endsWith('.txt')).sort().map((f) => `filters/${d}/${f}`));

  const filters = paths.map((path) => {
    const text = read(path);
    const query = parseFilter(text);
    const meta = parseMetadata(text);
    const reference = header(text, 'Referencia completa') ?? meta?.validation?.reference ?? null;
    return {
      path,
      family: path.split('/')[1],
      title: header(text, 'Filtro'),
      description: header(text, 'Descripci[oó]n'),
      role: roleOf[path] ?? null,
      registry_key: registryKey[path] ?? null,
      pair: pairOf(path, paths),
      exclusion: isNegation(query),
      embedded_date_limit: hasEmbeddedDateLimit(query),
      validation: /propia/i.test(text) ? 'author_made' : /adaptad/i.test(text) ? 'adapted_from_reference' : 'reference_cited',
      reference,
      metrics: meta?.validation?.metrics ?? null,
    };
  });

  const js = read('journal_filters_data.js');
  const jr = JSON.parse(js.slice(js.indexOf('{'), js.indexOf('\n};') + 2));
  const journals = Object.entries(jr).sort(([a], [b]) => a.localeCompare(b)).map(([id, j]) => ({
    id,
    path: `filters/journals/${id}.txt`,
    name: j.name ?? null,
    description: j.description ?? null,
    journal_count: j.journalCount ?? null,
    role: 'editorial',
  }));

  return {
    what: 'Every retrieval filter and journal list in this repository, with its default role. Generated by scripts/catalog.mjs; do not edit by hand.',
    contract_version: router.conformance?.contract_version ?? null,
    roles: 'Defined in neurosymbolic_router.json composition.roles. The role is a default: the question decides (composition.facet_roles).',
    validation_values: {
      author_made: 'The header says it is the author\'s own work. Never present it as validated.',
      adapted_from_reference: 'Adapted from a published filter. The stored version is not the validated one.',
      reference_cited: 'The header cites a reference. That alone does not prove the stored version is the validated one.',
    },
    counts: { retrieval_filters: filters.length, journal_lists: journals.length },
    filters,
    journal_lists: journals,
  };
}

export const serialize = (catalog) => `${JSON.stringify(catalog, null, 2)}\n`;

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const fresh = serialize(buildCatalog());
  const target = join(HERE, CATALOG_PATH);
  if (process.argv.includes('--check')) {
    const current = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== fresh) {
      console.error(`${CATALOG_PATH} no coincide con lo generado: node scripts/catalog.mjs`);
      process.exit(1);
    }
    console.log(`${CATALOG_PATH} al día.`);
  } else {
    writeFileSync(target, fresh);
    console.log(`${CATALOG_PATH}: ${JSON.parse(fresh).counts.retrieval_filters} filtros y ${JSON.parse(fresh).counts.journal_lists} listas de revistas.`);
  }
}
